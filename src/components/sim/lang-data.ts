/** Guesses the alphabet of a word. */
export function abcOf(s: string): Abc {
  if (/[Ա-֏]/.test(s)) return "hy";
  if (/[Ѐ-ӿ]/.test(s)) return "ru";
  return "en";
}

const VOWELS: Record<Abc, RegExp> = { hy: /ու|[աեէըիոօ]/giu, ru: /[аеёиоуыэюя]/giu, en: /[aeiouy]/giu };
/** Number of vowel sounds written in a word (Armenian ու counts once). */
export const vowelCount = (s: string) => (s.match(VOWELS[abcOf(s)]) ?? []).length;
/** Splits a word into letters, keeping Armenian ու together. */
export const lettersOf = (s: string) => s.match(/ու|Ու|[\s\S]/gu) ?? [];
const VOWEL1: Record<Abc, RegExp> = { hy: /^(ու|[աեէըիոօ])$/iu, ru: /^[аеёиоуыэюя]$/iu, en: /^[aeiouy]$/iu };
export const isVowel = (ch: string) => VOWEL1[abcOf(ch)].test(ch);
